// Usage: npm run images -- <folder> [<folder>…] [--concept <folder>]
//
// Converts every JPG/PNG in the given folders to responsive WebP in public/images and regenerates
// src/api/mock/data/images.generated.ts (slot id → files). Folders passed after --concept are
// AI "concept" renders of real places/people: they are tagged so the site shows a visible
// "Concept image" label until approved photographs replace them.
import sharp from 'sharp'
import { mkdirSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const OUT_DIR = 'public/images'
const TS_OUT = 'src/api/mock/data/images.generated.ts'
const WIDTHS = [640, 1024, 1600, 2400]

const sources = []
let concept = false
for (const arg of process.argv.slice(2)) {
  if (arg === '--concept') concept = true
  else sources.push({ dir: arg, concept })
}
if (!sources.length) {
  console.error('Usage: npm run images -- <folder> [<folder>…] [--concept <folder>]')
  process.exit(1)
}

mkdirSync(OUT_DIR, { recursive: true })
const entries = {}
let bytes = 0

for (const { dir, concept: isConcept } of sources) {
  for (const file of readdirSync(dir).filter((f) => /\.(jpe?g|png)$/i.test(f)).sort()) {
    const slot = path.basename(file).replace(/\.(jpe?g|png)$/i, '')
    const input = path.join(dir, file)
    const meta = await sharp(input).metadata()
    const widths = [...new Set([...WIDTHS.filter((w) => w < meta.width), meta.width])].sort((a, b) => a - b)
    await Promise.all(
      widths.map(async (w) => {
        const out = path.join(OUT_DIR, `${slot}-${w}.webp`)
        await sharp(input).resize({ width: w, withoutEnlargement: true }).webp({ quality: 78, effort: 5 }).toFile(out)
        bytes += statSync(out).size
      }),
    )
    const max = widths[widths.length - 1]
    entries[slot] = {
      src: `/images/${slot}-${max}.webp`,
      srcSet: widths.map((w) => `/images/${slot}-${w}.webp ${w}w`).join(', '),
      width: meta.width,
      height: meta.height,
      ...(isConcept ? { concept: true } : {}),
    }
    console.log(`${slot}${isConcept ? ' (concept)' : ''}: ${widths.join('/')}`)
  }
}

const ts = `// Generated by "npm run images" (scripts/optimise-images.mjs) — do not edit by hand.
// Re-run it after adding images; keys are slot ids from docs/IMAGE_PROMPTS.md.
export interface ProvidedImage {
  src: string
  srcSet: string
  width: number
  height: number
  /** AI concept of a real place/person/event — shown with a visible label until a photo replaces it. */
  concept?: boolean
}

export const providedImages: Record<string, ProvidedImage> = ${JSON.stringify(entries, null, 2)}
`
writeFileSync(TS_OUT, ts)
const concepts = Object.values(entries).filter((e) => e.concept).length
console.log(`\n${Object.keys(entries).length} slots (${concepts} concept), ${(bytes / 1024 / 1024).toFixed(1)} MB of WebP in ${OUT_DIR}`)
