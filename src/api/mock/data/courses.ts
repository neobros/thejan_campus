/**
 * Course catalogue transcribed from The Centre of Excellence (international) course pages, checked
 * 14 Oct 2026 (see COE_13_Courses_Detailed_Source_Data.md). Per the client, the pages show **only
 * data present in that source document** — duration (study + holiday weeks), campus, code, units,
 * entry requirements, fees and related courses. Invented marketing content (learning outcomes,
 * "who it's for", careers, teaching/assessment detail) and sample intake dates are intentionally
 * omitted. Fees come from the provider's draft June 2026 schedule and are shown as indicative only.
 */
export interface CourseSeed {
  id: string
  slug: string
  title: string
  code: string | null
  level: string
  levelRank: number
  category: 'business' | 'english' | 'beauty' | 'hairdressing' | 'construction' | 'civil-construction'
  summary: string
  duration: string
  deliveryModes: DeliveryMode[]
  audiences: Audience[]
  campuses: string[]
  featured?: boolean
  image: ImageAsset
  overview: string
  intendedFor: string[]
  purpose?: string
  studyPattern?: string
  holidayBreakdown?: string
  teachingLanguage?: string
  outcomes: string[]
  modules: CourseModule[]
  moduleNote?: string
  entry?: Partial<EntryRequirements>
  delivery: Course['delivery']
  placement?: Course['placement']
  creditTransfer?: Course['creditTransfer']
  pathways: { furtherStudy: string[]; careers: string[] }
  /** Approved fee per audience. Omit an audience to show "Contact admissions for current fees". */
  fees: Partial<Record<Audience, { amount: string; basis: FeeBasis; additional?: FeeSchedule['additional'] }>>
  /** Intake starts as "months ahead" (first Monday of that month). Empty = no published dates. */
  intakeMonths: number[]
  /** Add an intake starting soon whose deadline has passed (shows the closed state). */
  closedIntakeSoon?: boolean
  /** Demo availability overrides keyed "campusSlug:intakeIndex". */
  statusOverrides?: Record<string, IntakeStatus>
  downloads?: string[]
  related?: string[]
}

