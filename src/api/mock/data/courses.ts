/**
 * DEMO DATA — sample courses for layout and workflow testing only. Titles, codes ("DEMO-…"),
 * modules and fees are illustrative and must be replaced with academic-team-approved content.
 * Entry requirements deliberately use placeholders: the specification forbids publishing guessed
 * scores, ages or qualifications (§5.8).
 */
export interface CourseSeed {
  id: string
  slug: string
  title: string
  code: string | null
  level: string
  levelRank: number
  category: 'business' | 'information-technology' | 'hospitality' | 'health' | 'english' | 'short-courses'
  summary: string
  duration: string
  deliveryModes: DeliveryMode[]
  audiences: Audience[]
  campuses: string[]
  featured?: boolean
  image: ImageAsset
  overview: string
  intendedFor: string[]
  purpose?: string
  studyPattern?: string
  holidayBreakdown?: string
  teachingLanguage?: string
  outcomes: string[]
  modules: CourseModule[]
  moduleNote?: string
  entry?: Partial<EntryRequirements>
  delivery: Course['delivery']
  placement?: Course['placement']
  creditTransfer?: Course['creditTransfer']
  pathways: { furtherStudy: string[]; careers: string[] }
  /** Approved fee per audience. Omit an audience to show "Contact admissions for current fees". */
  fees: Partial<Record<Audience, { amount: string; basis: FeeBasis; additional?: FeeSchedule['additional'] }>>
  /** Intake starts as "months ahead" (first Monday of that month). */
  intakeMonths: number[]
  /** Add an intake starting soon whose deadline has passed (shows the closed state). */
  closedIntakeSoon?: boolean
  /** Demo availability overrides keyed "campusSlug:intakeIndex". */
  statusOverrides?: Record<string, IntakeStatus>
  downloads?: string[]
  related?: string[]
}

