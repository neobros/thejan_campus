/** `relatedForms` is resolved by the mock API from `relatedFormSlugs` (resource slugs). */
export type PolicySeed = Omit<Policy, 'relatedForms'> & { relatedFormSlugs: string[] }

/* ------------------------------------------------------------------------------------------------
 * Policies — content requirements, not drafted legal text. Each body shows the sections the
 * approved policy must contain; bracketed items are completed by the client's authorised reviewer.
 * ---------------------------------------------------------------------------------------------- */

interface PolicyOutline {
  purpose: string
  scope: string
  statements: string[]
  procedure: string[]
  responsibilities: [role: string, duty: string][]
  related: string[]
  contact: string
}

function policyBody(outline: PolicyOutline, effectiveDate: string, approver: string) {
  return [
    '> **Demo structure.** This page shows the content the approved policy must include. Replace each bracketed item with wording approved by AIT before publication.',
    '## Purpose',
    outline.purpose,
    '## Scope',
    outline.scope,
    '## Policy statements',
    outline.statements.map((item) => `- ${item}`).join('\n'),
    '## Procedure',
    outline.procedure.map((item, index) => `${index + 1}. ${item}`).join('\n'),
    '## Responsibilities',
    ['| Role | Responsibility |', '| --- | --- |', ...outline.responsibilities.map(([role, duty]) => `| ${role} | ${duty} |`)].join('\n'),
    '## Related documents',
    outline.related.map((item) => `- ${item}`).join('\n'),
    '## Contact',
    outline.contact,
    '## Version history',
    [
      '| Version | Effective date | Summary of changes | Approved by |',
      '| --- | --- | --- | --- |',
      `| ${DEMO_VERSION} | ${effectiveDate} | Demo structure prepared for client review | ${approver} |`,
    ].join('\n'),
  ].join('\n\n')
}

